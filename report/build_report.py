h("5. Task 3: physics consistency")
para("Task 3 has no rows of its own, so the only lever is the Task 1 answer. The score is S_physics = (1/3) S_FD + (2/3) S_LWR. With the official scorer our S_FD was about 0.987. S_LWR needs hidden boundary flows, so we could not measure it locally, and we treated any change as a guess unless a proxy agreed.")
para("The change we kept (density A): where both the reading 5 minutes before and the reading 5 minutes after a cell are released, we move the predicted density k = q / v toward those two neighbours with a 3% weight each, keep the speed, and recompute flow as k x v. In congested cells (speed below 0.58 x free speed), flow above the triangular fundamental-diagram envelope is nudged 4% toward it. The leaderboard effect was tiny (public 0.84862 to 0.84867), so we count it as safe rather than as a big win.")
para("What did not work: a stronger version that pulled toward a linear interpolation of the released density (density B) scored worse (0.84690 against 0.84867). A direct LWR projection and gap anchoring or smoothing cost state accuracy for no clear physics gain and were dropped.")

h("6. Task 4: ODME")
para("The organizers release a reference path-flow method. Our first version used a file fit to the training months' link counts. The link-count term is much better when the file is fit to the counts of the month being scored, and the validation and private months each release their own link counts. Switching to the own-month counts raised the link-count score from about 0.965 to 0.9999 on validation, and the total from 0.79522 to 0.82680. We estimate S_ODME at about 0.99, so there is little left to gain there.")

