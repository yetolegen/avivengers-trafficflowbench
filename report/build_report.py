h("4. Task 2: queue prediction")
h("4.1 Why it was stuck", 2)
para("Task 2 stayed near 0.715 for a long time. We checked row order, keys and labels and found no bug. The cause we found in the data: between two training months, about 4.6 of the top-5 jam links are the same, but between a training month and the validation or private month only about 2.7 of 5 are the same. Jams sit in different places, so features like \"this link is usually jammed at this hour\" break. A \"same as the last reading\" baseline scores 0.2518 on validation against 0.307 on our training windows, so the scored month is also simply harder.")
h("4.2 Method", 2)
bullets([
    "Target: a link is queued when speed is at or below 0.60 x free-flow speed. Windows are either onset (no queue in the history, queue in the horizon) or ongoing (a queue at T). Both count equally.",
    "Training windows: we rebuilt onset and ongoing windows from the training data using the rules the organizers describe, and trained LightGBM binary classifiers on per-link, per-horizon rows.",
    "Recent-days features: how often this link was jammed around this time over the previous 7 and 28 days, built on one timeline across train, validation and private. They only use days before the window, so the model stays causal, and they adapt to a month where jams moved.",
    "Expected-IoU decoder: sort the cells of a window by jam probability and flag the top k, where k maximises the expected IoU, instead of using a fixed 0.5 cutoff. For onset windows only the T+30 cells are flagged, and at least one cell always is.",
    "Dedicated onset model: onset windows only matter at T+30, so a separate LightGBM and CatBoost pair trained only on those cells (blended 50/50 with the shared model) learns which bottleneck breaks first instead of sharing capacity with ongoing queues.",
    "Causality: the award review reruns Task 2 with every row after T removed. Our features use only the history before T, the row at T, and earlier days.",
])
